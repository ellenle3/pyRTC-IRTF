import math

D2PI = 2.0 * math.pi
DPIBY2 = math.pi / 2.0
DD2R = math.pi / 180.0  # degrees to radians
DR2D = 180.0 / math.pi  # radians to degrees
DAS2R = math.pi / (180.0 * 3600.0)  # arcseconds to radians
DR2AS = (180.0 * 3600.0) / math.pi  # radians to arcseconds
DH2R = math.pi / 12.0  # radians to hours
DR2H = 12.0 / math.pi  # hours to radians